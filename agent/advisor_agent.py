def _call_gemini_advisor(
    telemetry_dict: Dict[str, Any],
    api_key: str,
    model_name: str = "gemini-2.5-flash"
) -> AdvisorReport:
    """Invoke Google Gemini Chat Completion via OpenAI SDK with structured JSON output."""
    clean_key = clean_api_key(api_key)
    models_to_try = [model_name, "gemini-2.0-flash", "gemini-1.5-flash"]
    last_err = None

    for m in models_to_try:
        try:
            return _call_openai_compatible_advisor(
                telemetry_dict,
                api_key=clean_key,
                model_name=m,
                base_url="https://generativelanguage.googleapis.com/v1beta/openai/",
            )
        except Exception as e:
            last_err = e
            err_str = str(e).lower()
            if "404" in err_str or "not found" in err_str or "unrecognized model" in err_str:
                continue
            raise e

    if last_err:
        raise last_err
    raise RuntimeError("Failed to query Gemini with all available models.")


