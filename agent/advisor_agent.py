def filter_telemetry_thresholds(telemetry_dict: Dict[str, Any]) -> Dict[str, Any]:
    """Filter out false positives from telemetry (e.g., from legacy or unfiltered JSON snapshots).

    Enforces:
    - vacuum_bloat_candidates: dead_tup_ratio >= 5.0 and n_dead_tup > 5000.
    - stale_stats_candidates: n_mod_since_analyze > 10000 and (n_mod_since_analyze / max(n_live_tup, 1)) >= 0.05.
    """
    filtered = dict(telemetry_dict)

    bloat = filtered.get("vacuum_bloat_candidates") or []
    filtered_bloat = []
    for b in bloat:
        dead_ratio = float(b.get("dead_tup_ratio") or 0.0)
        dead_tup = int(b.get("n_dead_tup") or 0)
        if dead_ratio >= 5.0 and dead_tup > 5000:
            filtered_bloat.append(b)
    filtered["vacuum_bloat_candidates"] = filtered_bloat

    stale = filtered.get("stale_stats_candidates") or []
    filtered_stale = []
    for s in stale:
        mods = int(s.get("n_mod_since_analyze") or 0)
        live = max(int(s.get("n_live_tup") or 1), 1)
        mod_ratio = mods / float(live)
        if mods > 10000 and mod_ratio >= 0.05:
            filtered_stale.append(s)
    filtered["stale_stats_candidates"] = filtered_stale

    if "summary" in filtered and isinstance(filtered["summary"], dict):
        summary_copy = dict(filtered["summary"])
        summary_copy["total_vacuum_bloat_candidates"] = len(filtered_bloat)
        summary_copy["total_stale_stats_candidates"] = len(filtered_stale)
        filtered["summary"] = summary_copy

    return filtered


def generate_deterministic_diagnosis(telemetry: Dict[str, Any]) -> AdvisorReport:
    """Generate an AdvisorReport using deterministic database reliability rules.

    Provides an instant, robust fallback when an LLM API key is not configured
    or when API rate limits/network issues occur.
    """
    telemetry = filter_telemetry_thresholds(telemetry)
    findings: List[Finding] = []
    remediation_statements: List[str] = [
        "-- ====================================================================",
        "-- pg-copilot: Consolidated Safe Production Remediation Script",
        "-- Generated by Principal PostgreSQL Database Reliability Engineer Agent",
        "-- NOTE: CONCURRENTLY operations cannot run inside a multi-statement transaction block.",
        "-- Execute each statement independently in your migration pipeline or psql session.",
        "-- ====================================================================\n",
    ]

    penalty = 0

    # 1. Analyze Vacuum Bloat
    bloat_tables = telemetry.get("vacuum_bloat_candidates", [])
    vacuumed_targets = set()
    for b in bloat_tables:
        table_name = b.get("relname", "unknown")
        schema_name = b.get("schemaname", "public")
        dead_ratio = float(b.get("dead_tup_ratio", 0.0))
        dead_tup = int(b.get("n_dead_tup", 0))
        live_tup = int(b.get("n_live_tup", 0))

        severity: Literal["CRITICAL", "WARNING"] = "CRITICAL" if dead_ratio >= 30.0 else "WARNING"
        penalty += 25 if severity == "CRITICAL" else 15

        target = f"{schema_name}.{table_name}"
        vacuumed_targets.add(target)
        rca = (
            f"Severe MVCC dead tuple accumulation detected on '{target}' ({dead_ratio}% dead tuples, "
            f"{dead_tup:,} dead rows vs {live_tup:,} live rows). In PostgreSQL, UPDATE and DELETE "
            f"operations do not overwrite disk blocks in-place; they write new tuple versions and mark old "
            f"versions as dead. Because autovacuum has not reclaimed these dead versions, the table suffers "
            f"from physical heap bloat, increased disk I/O, cache pollution in shared_buffers, and degraded "
            f"sequential/index scan throughput."
        )

        sql = (
            f"-- Step 1: Reclaim dead tuple space non-blockingly\n"
            f"VACUUM (VERBOSE, ANALYZE) {target};\n\n"
            f"-- Step 2: Tune autovacuum to trigger more aggressively on high-write table\n"
            f"ALTER TABLE {target} SET (\n"
            f"    autovacuum_vacuum_scale_factor = 0.05,\n"
            f"    autovacuum_vacuum_threshold = 500,\n"
            f"    autovacuum_vacuum_cost_limit = 1000\n"
            f");"
        )

        locking = (
            "Safe for production: Standard `VACUUM` takes only a ShareUpdateExclusiveLock, allowing "
            "concurrent SELECTs, INSERTs, UPDATEs, and DELETEs. It will NOT block application traffic. "
            "(Avoid VACUUM FULL, which demands an AccessExclusiveLock and locks out all queries)."
        )

        findings.append(Finding(
            category="VACUUM",
            severity=severity,
            target_object=target,
            root_cause_analysis=rca,
            recommended_sql=sql,
            locking_impact=locking
        ))

        remediation_statements.append(f"-- [VACUUM & BLOAT] Remediation for {target}")
        remediation_statements.append(sql + "\n")

    # 2. Analyze Missing Index Candidates (Heavy Seq Scans)
    missing_idx_tables = telemetry.get("missing_index_candidates", [])
    for m in missing_idx_tables:
        table_name = m.get("relname", "unknown")
        schema_name = m.get("schemaname", "public")
        seq_scan = m.get("seq_scan", 0)
        seq_tup_read = m.get("seq_tup_read", 0)
        avg_tup = m.get("avg_tup_per_seq_scan", 0)

        raw_candidates = m.get("candidate_columns") or []
        if isinstance(raw_candidates, str):
            try:
                raw_candidates = json.loads(raw_candidates)
            except Exception:
                raw_candidates = [c.strip() for c in raw_candidates.split(",") if c.strip()]

        raw_existing = m.get("existing_indexed_columns") or []
        if isinstance(raw_existing, str):
            try:
                raw_existing = json.loads(raw_existing)
            except Exception:
                raw_existing = [c.strip() for c in raw_existing.split(",") if c.strip()]

        # Normalize candidates to dict objects with column_name, data_type, n_distinct, null_frac, null_pct
        parsed_candidates = []
        for c in raw_candidates:
            if isinstance(c, dict):
                col_name = c.get("column_name") or c.get("attname")
                if col_name:
                    raw_null = c.get("null_pct")
                    if raw_null is not None:
                        null_pct = float(raw_null)
                        null_frac = null_pct / 100.0
                    else:
                        null_frac = float(c.get("null_frac") or 0.0)
                        null_pct = null_frac * 100.0 if null_frac <= 1.0 else null_frac

                    parsed_candidates.append({
                        "column_name": col_name,
                        "data_type": c.get("data_type"),
                        "n_distinct": c.get("n_distinct", 0),
                        "null_frac": null_frac,
                        "null_pct": null_pct,
                    })
            elif isinstance(c, str) and c.strip():
                parsed_candidates.append({
                    "column_name": c.strip(),
                    "data_type": None,
                    "n_distinct": -1,
                    "null_frac": 0.0,
                    "null_pct": 0.0,
                })

        existing_set = set(raw_existing)
        active_candidates = [c for c in parsed_candidates if c["column_name"] not in existing_set]
        if not active_candidates and parsed_candidates:
            active_candidates = parsed_candidates

        # Filter out candidate columns where null_pct >= 90.0 or n_distinct == 0 or n_distinct == 1
        # In PostgreSQL pg_stats:
        # - n_distinct == 0: unanalyzed or completely empty table/column (e.g. account_org_id with 100% nulls)
        # - n_distinct == 1: constant column with only 1 unique value across millions of rows (un-indexable)
        # - n_distinct < 0: negative fraction of total rows (e.g. -1.0 is completely unique), highly selective
        # - n_distinct > 1: estimated distinct value count
        valid_candidates = []
        for c in active_candidates:
            pct = float(c.get("null_pct", 0.0) or 0.0)
            n_dist = c.get("n_distinct", 0)
            try:
                n_dist_num = float(n_dist) if n_dist is not None else 0
            except (ValueError, TypeError):
                n_dist_num = 0
            if pct < 90.0 and n_dist_num not in (0, 1, 0.0, 1.0):
                valid_candidates.append(c)

        severity = "CRITICAL" if seq_tup_read > 1_000_000 else "WARNING"
        penalty += 25 if severity == "CRITICAL" else 15

        target = f"{schema_name}.{table_name}"

        if valid_candidates:
            # Case A: Real unindexed candidate columns with viable selectivity discovered
            top_cols = valid_candidates[:2]
            col_names = [c["column_name"] for c in top_cols]
            cols_str = ", ".join(col_names)
            idx_name = f"idx_{table_name}_{'_'.join(col_names)}"
            sql = (
                f"-- Create secondary index concurrently on discovered candidate columns to eliminate sequential scans\n"
                f"CREATE INDEX CONCURRENTLY IF NOT EXISTS {idx_name}\n"
                f"ON {target} ({cols_str});"
            )

            # Mention existing_indexed_columns and n_distinct / null_pct in root cause
            col_details = []
            for c in top_cols:
                null_pct = round(float(c.get("null_pct", 0.0)), 1)
                n_dist = c.get("n_distinct", 0)
                dist_str = f"n_distinct={n_dist}" if n_dist else "stats pending"
                col_details.append(f"{c['column_name']} ({dist_str}, nulls={null_pct}%)")

            existing_str = ", ".join(raw_existing) if raw_existing else "none"

            rca = (
                f"Repeated full heap sequential scans on table '{target}' ({seq_scan} sequential scans, "
                f"{seq_tup_read:,} total tuples read, averaging {avg_tup:,.1f} rows read per scan). "
                f"Because no covering or selective secondary index exists for queried filter conditions, the "
                f"PostgreSQL query optimizer is forced to execute full table scans, churning memory pages in "
                f"shared_buffers and causing CPU spikes. "
                f"Catalog telemetry identified high-selectivity unindexed candidate columns: {'; '.join(col_details)}. "
                f"Existing leading indexed columns on table: {existing_str}."
            )
        else:
            # Case B: Legacy / minimal snapshot without column metadata OR all candidate columns disqualified (>90% nulls / n_distinct in 0, 1)
            disqualified_note = ""
            if parsed_candidates:
                disqualified_note = " Discovered catalog columns were disqualified due to zero/single cardinality (n_distinct in 0, 1) or excessive null ratios (>90% NULL)."

            sql = (
                f"-- Step 1: Pre-check column selectivity and query filter predicates from pg_stats\n"
                f"-- SELECT attname, n_distinct, null_frac, most_common_vals FROM pg_stats WHERE schemaname = '{schema_name}' AND tablename = '{table_name}';\n\n"
                f"-- Step 2: Create secondary index concurrently with high-selectivity WHERE/JOIN columns\n"
                f"CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_{table_name}_covering\n"
                f"ON {target} (<filter_col_1>, <filter_col_2>); -- Replace with high-selectivity WHERE/JOIN columns from pg_stats"
            )
            rca = (
                f"Repeated full heap sequential scans on table '{target}' ({seq_scan} sequential scans, "
                f"{seq_tup_read:,} total tuples read, averaging {avg_tup:,.1f} rows read per scan). "
                f"Because no covering or selective secondary index exists for queried filter conditions, the "
                f"PostgreSQL query optimizer is forced to execute full table scans, churning memory pages in "
                f"shared_buffers and causing CPU spikes.{disqualified_note} "
                f"Inspect filter predicates in pg_stat_statements and pg_stats for {target} to identify optimal index key columns."
            )

        locking = (
            "Safe for production: `CREATE INDEX CONCURRENTLY` builds the B-tree index in two separate "
            "passes without taking an AccessExclusiveLock. Concurrent transactions can read and write to "
            f"'{target}' unhindered throughout index creation."
        )

        findings.append(Finding(
            category="SEQ_SCAN",
            severity=severity,
            target_object=target,
            root_cause_analysis=rca,
            recommended_sql=sql,
            locking_impact=locking
        ))

        remediation_statements.append(f"-- [MISSING INDEX] Remediation for {target}")
        remediation_statements.append(sql + "\n")

    # 3. Analyze Unused Indexes
    unused_indexes = telemetry.get("unused_indexes", [])
    for u in unused_indexes:
        table_name = u.get("table_name", "unknown")
        index_name = u.get("index_name", "unknown")
        schema_name = u.get("schemaname", "public")
        size_pretty = u.get("index_size_pretty", "unknown")
        size_bytes = u.get("index_size_bytes", 0)

        severity = "WARNING" if size_bytes > 2_000_000 else "INFO"
        penalty += 10 if severity == "WARNING" else 5

        target = f"{schema_name}.{index_name}"
        rca = (
            f"Redundant/unused B-tree index '{index_name}' on table '{table_name}' ({size_pretty}). "
            f"Catalog telemetry records 0 index scans (idx_scan = 0). Every INSERT, UPDATE, and DELETE "
            f"on '{table_name}' incurs write amplification and WAL overhead to maintain this unused index "
            f"tree, while also consuming RAM in shared_buffers and operating system page caches."
        )

        sql = f"DROP INDEX CONCURRENTLY IF EXISTS {schema_name}.{index_name};"

        locking = (
            "Safe for production: `DROP INDEX CONCURRENTLY` drops the index without taking an exclusive "
            f"lock on '{table_name}'. It acquires only a ShareUpdateExclusiveLock, preventing query stalls."
        )

        findings.append(Finding(
            category="INDEX",
            severity=severity,
            target_object=target,
            root_cause_analysis=rca,
            recommended_sql=sql,
            locking_impact=locking
        ))

        remediation_statements.append(f"-- [UNUSED INDEX] Drop {target}")
        remediation_statements.append(sql + "\n")

    # 4. Analyze Stale Statistics
    stale_tables = telemetry.get("stale_stats_candidates", [])
    for s in stale_tables:
        table_name = s.get("relname", "unknown")
        schema_name = s.get("schemaname", "public")
        mod_count = s.get("n_mod_since_analyze", 0)
        live_tup = s.get("n_live_tup", 0)
        last_analyze = s.get("last_analyze")

        severity = "WARNING" if mod_count > 20000 else "INFO"
        penalty += 10 if severity == "WARNING" else 5

        target = f"{schema_name}.{table_name}"
        last_an_str = last_analyze if last_analyze else "Never"
        rca = (
            f"Stale optimizer statistics on '{target}' ({mod_count:,} modifications since last analyze; "
            f"last analyzed: {last_an_str}). PostgreSQL cost-based optimizer uses table statistics "
            f"(MCV lists, histograms, distinct count estimates) to generate query plans. Stale statistics "
            f"lead to plan regressions, such as picking slow Nested Loop joins over Hash Joins or ignoring "
            f"viable indexes due to row estimate discrepancies."
        )

        already_vacuum_analyzed = target in vacuumed_targets

        if already_vacuum_analyzed:
            sql = (
                f"-- Step 1: Note that VACUUM (VERBOSE, ANALYZE) recommended above already refreshed statistics for {target}.\n"
                f"-- (If running standalone without vacuum: ANALYZE VERBOSE {target};)\n\n"
                f"-- Step 2: Lower autovacuum analyze scale factor to update stats more frequently\n"
                f"ALTER TABLE {target} SET (\n"
                f"    autovacuum_analyze_scale_factor = 0.05,\n"
                f"    autovacuum_analyze_threshold = 250\n"
                f");"
            )
            remediation_sql_for_script = (
                f"-- Note: Standalone ANALYZE skipped because VACUUM (VERBOSE, ANALYZE) above already refreshed planner stats.\n"
                f"-- Lower autovacuum analyze scale factor to update stats more frequently\n"
                f"ALTER TABLE {target} SET (\n"
                f"    autovacuum_analyze_scale_factor = 0.05,\n"
                f"    autovacuum_analyze_threshold = 250\n"
                f");"
            )
        else:
            sql = (
                f"-- Refresh table statistics non-blockingly\n"
                f"ANALYZE VERBOSE {target};\n\n"
                f"-- Lower autovacuum analyze scale factor to update stats more frequently\n"
                f"ALTER TABLE {target} SET (\n"
                f"    autovacuum_analyze_scale_factor = 0.05,\n"
                f"    autovacuum_analyze_threshold = 250\n"
                f");"
            )
            remediation_sql_for_script = sql

        locking = (
            "Safe for production: `ANALYZE` acquires a ShareUpdateExclusiveLock, sampling a small random "
            "set of table pages without blocking concurrent reads or writes."
        )

        findings.append(Finding(
            category="STATS",
            severity=severity,
            target_object=target,
            root_cause_analysis=rca,
            recommended_sql=sql,
            locking_impact=locking
        ))

        remediation_statements.append(f"-- [STALE STATS] Remediation for {target}")
        remediation_statements.append(remediation_sql_for_script + "\n")

    # Calculate overall health score
    health_score = max(5, min(100, 100 - penalty))

    summary = (
        f"Database Health Score: {health_score}/100. Diagnostic telemetry identified {len(findings)} "
        f"performance and reliability issues: {len(bloat_tables)} vacuum/bloat hotspot(s), "
        f"{len(missing_idx_tables)} table(s) suffering high sequential scans, {len(unused_indexes)} "
        f"redundant index(es) causing write amplification, and {len(stale_tables)} table(s) with stale statistics. "
        f"All proposed remediations strictly enforce non-blocking DDL (CONCURRENTLY, ShareUpdateExclusiveLock) "
        f"to safeguard production availability."
    )

    consolidated_sql = "\n".join(remediation_statements)

    return AdvisorReport(
        health_score=health_score,
        executive_summary=summary,
        findings=findings,
        consolidated_remediation_sql=consolidated_sql
    )


