class Finding(BaseModel):
    """Specific diagnostic finding and non-blocking remediation recommendation."""
    category: Literal["INDEX", "VACUUM", "STATS", "SEQ_SCAN"]
    severity: Literal["CRITICAL", "WARNING", "INFO"]
    target_object: str
    root_cause_analysis: str
    recommended_sql: str
    locking_impact: str

    if PYDANTIC_V2:
        @field_validator("recommended_sql")
        @classmethod
        def validate_non_blocking_ddl(cls, v: str, info) -> str:
            category = info.data.get("category") if hasattr(info, "data") else None
            sql_upper = v.upper()
            if category == "INDEX" and "DROP INDEX" in sql_upper:
                if "CONCURRENTLY" not in sql_upper:
                    raise ValueError("Index drop recommendations must enforce CONCURRENTLY to prevent blocking production transactions.")
            return v
    else:
        @validator("recommended_sql")
        def validate_non_blocking_ddl(cls, v: str, values: Dict[str, Any]) -> str:
            category = values.get("category")
            sql_upper = v.upper()
            if category == "INDEX" and "DROP INDEX" in sql_upper:
                if "CONCURRENTLY" not in sql_upper:
                    raise ValueError("Index drop recommendations must enforce CONCURRENTLY to prevent blocking production transactions.")
            return v


class AdvisorReport(BaseModel):
    """Consolidated PostgreSQL Health and Performance Advisor Report."""
    health_score: int = Field(..., ge=0, le=100, description="Overall database health score between 0 and 100")
    executive_summary: str
    findings: List[Finding]
    consolidated_remediation_sql: str


