def clean_api_key(api_key: Optional[str]) -> str:
    """Clean and extract raw API key string from quotes, prefixes, or export statements."""
    if not api_key:
        return ""
    k = str(api_key).strip()
    # Remove leading/trailing quotes
    if (k.startswith('"') and k.endswith('"')) or (k.startswith("'") and k.endswith("'")):
        k = k[1:-1].strip()
    # Remove 'Bearer '
    if k.lower().startswith("bearer "):
        k = k[7:].strip()
    # Remove 'export VAR=...'
    if k.startswith("export "):
        k = k[7:].strip()
    # If pasted as KEY=value
    if "=" in k and not (k.startswith("gsk_") or k.startswith("sk-") or k.startswith("AIza")):
        parts = k.split("=", 1)
        val = parts[1].strip().strip('"').strip("'")
        if val:
            k = val
    return k.strip()


def detect_provider_from_key(api_key: Optional[str]) -> Optional[str]:
    """Auto-detect LLM provider from the API key prefix or structure.

    Prefix rules:
      - 'gsk_*'                             -> 'groq'
      - 'AIza*' / 'aiza*' / Google 39-chars -> 'gemini'
      - 'sk-ant-*'                          -> 'anthropic'
      - 'sk-*'                              -> 'openai'
    """
    if not api_key:
        return None
    k = clean_api_key(api_key)
    if not k:
        return None

    if k.startswith("gsk_"):
        return "groq"
    if k.startswith("sk-ant-"):
        return "anthropic"
    if k.startswith("sk-"):
        return "openai"
    if (
        k.startswith("AIza")
        or k.startswith("aiza")
        or k.startswith("AI")
        or k.startswith("gm-")
        or k.startswith("gemini")
        or k.startswith("ya29.")
        or (len(k) == 39 and all(c.isalnum() or c in "-_" for c in k))
    ):
        return "gemini"

    return None


def _call_openai_compatible_advisor(
    telemetry_dict: Dict[str, Any],
    api_key: str,
    model_name: str,
    base_url: Optional[str] = None
) -> AdvisorReport:
    """Invoke OpenAI or OpenAI-compatible Chat Completion API (Groq, Gemini, etc.) with structured JSON output."""
    from openai import OpenAI

    clean_key = clean_api_key(api_key)
    try:
        import httpx
        http_client = httpx.Client()
        client = OpenAI(api_key=clean_key, base_url=base_url, http_client=http_client) if base_url else OpenAI(api_key=clean_key, http_client=http_client)
    except Exception:
        client = OpenAI(api_key=clean_key, base_url=base_url) if base_url else OpenAI(api_key=clean_key)
    system_prompt = build_system_prompt()
    prompt = (
        f"Here is the PostgreSQL catalog diagnostic telemetry JSON:\n\n"
        f"```json\n{json.dumps(telemetry_dict, indent=2)}\n```\n\n"
        f"Analyze this telemetry and output the complete diagnostic report conforming to the JSON schema."
    )

    response = client.chat.completions.create(
        model=model_name,
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": prompt},
        ],
        response_format={"type": "json_object"},
        temperature=0.2,
    )

    content = (response.choices[0].message.content or "").strip()
    if content.startswith("```json"):
        content = content[7:]
    elif content.startswith("```"):
        content = content[3:]
    if content.endswith("```"):
        content = content[:-3]
    content = content.strip()

    data = json.loads(content)
    return AdvisorReport(**data)


