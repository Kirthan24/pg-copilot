def _call_anthropic_advisor(
    telemetry_dict: Dict[str, Any],
    api_key: str,
    model_name: str = "claude-3-5-sonnet-latest"
) -> AdvisorReport:
    """Invoke Anthropic Claude with tool-use / structured JSON schema."""
    import anthropic

    client = anthropic.Anthropic(api_key=api_key)
    system_prompt = build_system_prompt()
    user_prompt = (
        f"Here is the PostgreSQL catalog diagnostic telemetry JSON:\n\n"
        f"```json\n{json.dumps(telemetry_dict, indent=2)}\n```\n\n"
        f"Analyze this telemetry using your DBRE knowledge base and output the complete diagnostic report conforming to the JSON schema."
    )

    tools = [
        {
            "name": "submit_advisor_report",
            "description": "Submit the completed PostgreSQL health and performance advisor report.",
            "input_schema": {
                "type": "object",
                "properties": {
                    "health_score": {
                        "type": "integer",
                        "minimum": 0,
                        "maximum": 100,
                        "description": "Overall database health score between 0 and 100",
                    },
                    "executive_summary": {
                        "type": "string",
                        "description": "Concise executive summary of database health and issues",
                    },
                    "findings": {
                        "type": "array",
                        "items": {
                            "type": "object",
                            "properties": {
                                "category": {
                                    "type": "string",
                                    "enum": ["INDEX", "VACUUM", "STATS", "SEQ_SCAN"],
                                },
                                "severity": {
                                    "type": "string",
                                    "enum": ["CRITICAL", "WARNING", "INFO"],
                                },
                                "target_object": {"type": "string"},
                                "root_cause_analysis": {"type": "string"},
                                "recommended_sql": {"type": "string"},
                                "locking_impact": {"type": "string"},
                            },
                            "required": [
                                "category",
                                "severity",
                                "target_object",
                                "root_cause_analysis",
                                "recommended_sql",
                                "locking_impact",
                            ],
                        },
                    },
                    "consolidated_remediation_sql": {
                        "type": "string",
                        "description": "Complete executable non-blocking SQL script",
                    },
                },
                "required": [
                    "health_score",
                    "executive_summary",
                    "findings",
                    "consolidated_remediation_sql",
                ],
            },
        }
    ]

    response = client.messages.create(
        model=model_name,
        max_tokens=4096,
        system=system_prompt,
        messages=[{"role": "user", "content": user_prompt}],
        tools=tools,
        tool_choice={"type": "tool", "name": "submit_advisor_report"},
    )

    for block in response.content:
        if block.type == "tool_use" and block.name == "submit_advisor_report":
            return AdvisorReport(**block.input)

    raise ValueError("Anthropic response did not contain expected tool_use block.")


def generate_ai_diagnosis(
    telemetry_dict: Dict[str, Any],
    api_key: Optional[str] = None,
    provider: Optional[str] = None,
    model: Optional[str] = None
) -> AdvisorReport:
    """Generate an AI-driven or deterministic PostgreSQL diagnostic report.

    Supports Groq, Google Gemini, Anthropic Claude, and OpenAI with auto-detection
    from API key prefixes:
      - 'gsk_*'     -> Groq (llama-3.3-70b-versatile)
      - 'AIza*'     -> Google Gemini (gemini-2.5-flash)
      - 'sk-ant-*'  -> Anthropic Claude (claude-3-5-sonnet-latest)
      - 'sk-*'      -> OpenAI (gpt-4o-mini)
      - empty / fail -> Graceful fallback to upgraded Deterministic Engine

    Args:
        telemetry_dict: The dictionary output from collect_full_telemetry().
        api_key: Optional API key for LLM provider.
        provider: Optional explicit provider override ('groq', 'gemini', 'anthropic', 'openai', or 'deterministic').
        model: Optional model override.

    Returns:
        AdvisorReport: A validated Pydantic model with health score, findings,
                       and production-safe remediation DDL.
    """
    telemetry_dict = filter_telemetry_thresholds(telemetry_dict)

    prov_str = (provider or "").lower().strip()
    if prov_str == "deterministic":
        return generate_deterministic_diagnosis(telemetry_dict)

    # Resolve API key from argument or environment variables
    resolved_key = clean_api_key(api_key)
    if not resolved_key or resolved_key == "your_llm_api_key_here":
        resolved_key = clean_api_key(
            os.getenv("GEMINI_API_KEY")
            or os.getenv("GOOGLE_API_KEY")
            or os.getenv("GROQ_API_KEY")
            or os.getenv("ANTHROPIC_API_KEY")
            or os.getenv("OPENAI_API_KEY")
            or os.getenv("LLM_API_KEY")
            or ""
        )

    if not resolved_key or resolved_key == "your_llm_api_key_here":
        return generate_deterministic_diagnosis(telemetry_dict)

    # Detect provider from key prefix
    detected_from_key = detect_provider_from_key(resolved_key)

    # Resolve target provider with safety rules:
    # 1. If explicit provider is "gemini", "groq", "openai", "deterministic", honor user's explicit choice!
    # 2. If provider is "anthropic" or "auto" but the key was detected as "gemini", "groq", or "openai",
    #    the key prefix auto-detection takes precedence so non-Anthropic keys are NEVER sent to Anthropic.
    # 3. If no detection matched and no valid provider was passed, fallback to gemini if it looks like Google key or deterministic.
    # Target provider resolution:
    # 1. Key prefix auto-detection takes top priority (e.g., Gemini keys are ALWAYS routed to Gemini, Groq to Groq)
    # 2. If key has no recognized prefix, honor user's explicit provider selection
    # 3. Otherwise fallback to Gemini (if looks like Google key) or deterministic
    if detected_from_key:
        target_provider = detected_from_key
    elif prov_str in ("gemini", "groq", "openai", "anthropic"):
        target_provider = prov_str
    elif prov_str and prov_str not in ("auto", "none"):
        target_provider = prov_str
    else:
        target_provider = "gemini" if (resolved_key.startswith("AI") or len(resolved_key) == 39) else "deterministic"

    # If deterministic mode was resolved, skip API calls directly
    if target_provider == "deterministic":
        return generate_deterministic_diagnosis(telemetry_dict)

    try:
        if target_provider == "groq":
            model_name = model or "llama-3.3-70b-versatile"
            return _call_groq_advisor(telemetry_dict, resolved_key, model_name)
        elif target_provider == "gemini":
            model_name = model or "gemini-2.5-flash"
            return _call_gemini_advisor(telemetry_dict, resolved_key, model_name)
        elif target_provider == "anthropic":
            model_name = model or "claude-3-5-sonnet-latest"
            return _call_anthropic_advisor(telemetry_dict, resolved_key, model_name)
        elif target_provider == "openai":
            model_name = model or "gpt-4o-mini"
            return _call_openai_advisor(telemetry_dict, resolved_key, model_name)
        else:
            model_name = model or "gemini-2.5-flash"
            return _call_gemini_advisor(telemetry_dict, resolved_key, model_name)
    except Exception as e:
        prov_label = target_provider.capitalize() if target_provider else "LLM"
        print(f"[WARN] {prov_label} invocation failed ({type(e).__name__}: {e}). Using deterministic fallback.")
        report = generate_deterministic_diagnosis(telemetry_dict)
        report.executive_summary = (
            f"[Deterministic Fallback Active - {prov_label} error: {e}] " + report.executive_summary
        )
        return report


